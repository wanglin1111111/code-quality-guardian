#!/usr/bin/env python3
"""
Test Case Generator — 测试用例自动生成器
支持单元测试、集成测试、边界值、异常场景
框架适配: pytest / Jest / JUnit / go test
"""

import re
import ast
import json
from dataclasses import dataclass, field, asdict
from typing import List, Optional, Dict, Tuple
from datetime import datetime, timezone, timedelta


@dataclass
class TestCase:
    name: str
    description: str
    category: str  # unit / integration / edge-case / exception
    code: str
    framework: str = "pytest"

    def to_dict(self):
        return asdict(self)


@dataclass
class TestSuite:
    source_function: str
    language: str
    framework: str
    test_cases: List[TestCase]
    coverage_estimate: str

    def to_code(self) -> str:
        """生成可运行的测试代码"""
        lines = []
        lines.append(f'# Auto-generated by Code Quality Guardian')
        lines.append(f'# Generated: {datetime.now(timezone(timedelta(hours=8))).isoformat()}')
        lines.append(f'# Source: {self.source_function}')
        lines.append(f'# Framework: {self.framework}')
        lines.append("")

        if self.framework == "pytest":
            lines.extend(self._pytest_header())
        elif self.framework == "jest":
            lines.extend(self._jest_header())
        elif self.framework == "go-test":
            lines.extend(self._go_header())

        for tc in self.test_cases:
            lines.append("")
            lines.append(tc.code)

        return "\n".join(lines)

    def _pytest_header(self) -> List[str]:
        return [
            "import pytest",
            "",
            f"# Import source module",
            f"# from your_module import {self.source_function}",
            "",
        ]

    def _jest_header(self) -> List[str]:
        return [
            "const { " + self.source_function + " } = require('./your_module');",
            "",
        ]

    def _go_header(self) -> List[str]:
        return [
            'package yourpackage_test',
            "",
            '"testing"',
            f'./yourpackage  // import path',
            "",
        ]

    def to_markdown(self) -> str:
        lines = []
        lines.append(f"## 🧪 测试用例生成报告\n")
        lines.append(f"**目标函数**: `{self.source_function}`")
        lines.append(f"**语言**: {self.language}")
        lines.append(f"**框架**: {self.framework}")
        lines.append(f"**预估覆盖**: {self.coverage_estimate}")
        lines.append(f"**用例数量**: {len(self.test_cases)}")
        lines.append("")

        # Group by category
        categories = {}
        for tc in self.test_cases:
            categories.setdefault(tc.category, []).append(tc)

        for cat, cases in categories.items():
            emoji = {"unit": "🔹", "integration": "🔸", "edge-case": "⚠️", "exception": "❌"}.get(cat, "•")
            lines.append(f"### {emoji} {cat} 测试 ({len(cases)} 个)\n")
            for tc in cases:
                lines.append(f"**{tc.name}**: {tc.description}")
                lines.append(f"```{self.language}")
                lines.append(tc.code)
                lines.append("```\n")

        return "\n".join(lines)


class TestGenerator:
    """测试用例自动生成器"""

    FRAMEWORK_PATTERNS = {
        "pytest": {"assert": "assert", "import": "import pytest", "decorator": "@pytest.mark.parametrize"},
        "jest": {"assert": "expect", "import": "", "decorator": ""},
        "go-test": {"assert": "if err != nil", "import": "import (\n\t\"testing\"\n)", "decorator": ""},
    }

    def __init__(self, language: str = "python", framework: str = "pytest"):
        self.language = language
        self.framework = framework
        self.test_cases: List[TestCase] = []

    def generate(self, function_code: str, function_name: str,
                 scenarios: Optional[List[str]] = None) -> TestSuite:
        """为指定函数生成测试用例"""
        self.test_cases = []

        # 解析函数签名
        sig = self._parse_signature(function_code)
        params = sig.get("params", [])
        return_type = sig.get("return_type", "unknown")

        # 如果没有指定场景，生成全套
        if scenarios is None:
            scenarios = ["normal", "edge", "boundary", "exception"]

        # 生成各种测试场景
        if "normal" in scenarios:
            self._generate_normal_cases(function_name, params, return_type)
        if "edge" in scenarios:
            self._generate_edge_cases(function_name, params, return_type)
        if "boundary" in scenarios:
            self._generate_boundary_cases(function_name, params, return_type)
        if "exception" in scenarios:
            self._generate_exception_cases(function_name, params, return_type)

        # 估算覆盖率
        coverage = self._estimate_coverage(len(self.test_cases))

        return TestSuite(
            source_function=function_name,
            language=self.language,
            framework=self.framework,
            test_cases=self.test_cases,
            coverage_estimate=coverage,
        )

    def _parse_signature(self, code: str) -> Dict:
        """解析函数签名"""
        result = {"params": [], "return_type": "unknown"}

        if self.language == "python":
            # Python: def func(a, b=1, c=None) -> str:
            match = re.search(r"def\s+(\w+)\s*\(([^)]*)\)(?:\s*->\s*(\w+))?\s*:", code)
            if match:
                params_str = match.group(2)
                for p in params_str.split(","):
                    p = p.strip()
                    if p and p != "self":
                        # 提取参数名
                        name = p.split("=")[0].split(":")[0].strip()
                        if name:
                            result["params"].append(name)
                result["return_type"] = match.group(3) or "unknown"

        elif self.language in ("javascript", "typescript"):
            # JS: function func(a, b) 或 const func = (a, b) =>
            match = re.search(r"(?:function\s+\w+|const\s+\w+\s*=\s*(?:\([^)]*\)|async\s*\([^)]*\)))\s*\(([^)]*)\)", code)
            if match:
                params_str = match.group(1)
                for p in params_str.split(","):
                    p = p.strip()
                    if p:
                        name = p.split("=")[0].split(":")[0].strip()
                        if name:
                            result["params"].append(name)

        elif self.language == "go":
            # Go: func Func(a int, b string) error
            match = re.search(r"func\s+(\w+)\s*\(([^)]*)\)\s*(\w+)", code)
            if match:
                params_str = match.group(2)
                for p in params_str.split(","):
                    p = p.strip()
                    if p:
                        name = p.split(" ")[0].strip()
                        if name:
                            result["params"].append(name)
                result["return_type"] = match.group(3)

        return result

    def _generate_normal_cases(self, func_name: str, params: List[str], return_type: str):
        """生成正常场景测试用例"""
        normal_values = self._get_normal_values(params)

        tc = TestCase(
            name=f"test_{func_name}_normal",
            description=f"正常输入场景，验证基本功能正确性",
            category="unit",
            framework=self.framework,
            code=self._build_test_code(func_name, params, normal_values, "正常场景"),
        )
        self.test_cases.append(tc)

    def _generate_edge_cases(self, func_name: str, params: List[str], return_type: str):
        """生成边界场景测试用例"""
        edge_cases = [
            ("空值测试", self._get_none_values(params)),
            ("零值测试", self._get_zero_values(params)),
            ("大数测试", self._get_large_values(params)),
        ]

        for desc, values in edge_cases:
            tc = TestCase(
                name=f"test_{func_name}_{desc.split('测试')[0].strip()}",
                description=desc,
                category="edge-case",
                framework=self.framework,
                code=self._build_test_code(func_name, params, values, desc),
            )
            self.test_cases.append(tc)

    def _generate_boundary_cases(self, func_name: str, params: List[str], return_type: str):
        """生成边界值测试用例"""
        boundary_cases = [
            ("最小值", self._get_min_values(params)),
            ("最大值", self._get_max_values(params)),
        ]

        for desc, values in boundary_cases:
            tc = TestCase(
                name=f"test_{func_name}_boundary_{desc}",
                description=f"边界值场景：{desc}",
                category="edge-case",
                framework=self.framework,
                code=self._build_test_code(func_name, params, values, f"边界值{desc}"),
            )
            self.test_cases.append(tc)

    def _generate_exception_cases(self, func_name: str, params: List[str], return_type: str):
        """生成异常场景测试用例"""
        exception_cases = [
            ("非法类型", self._get_type_mismatch_values(params)),
            ("负值", self._get_negative_values(params)),
        ]

        for desc, values in exception_cases:
            tc = TestCase(
                name=f"test_{func_name}_exception_{desc.split('场景')[0].strip() if '场景' in desc else desc}",
                description=f"异常输入场景：{desc}",
                category="exception",
                framework=self.framework,
                code=self._build_exception_test(func_name, params, values, desc),
            )
            self.test_cases.append(tc)

    def _build_test_code(self, func_name: str, params: List[str],
                         values: Dict[str, str], description: str) -> str:
        """构建测试代码"""
        if self.framework == "pytest":
            lines = [f'def test_{func_name}():']
            lines.append(f'    """{description}"""')
            lines.append(f'    # Arrange')
            for p, v in zip(params, [values.get(p, "None") for p in params]):
                lines.append(f"    {p} = {v}")
            lines.append(f'    # Act')
            call_params = ", ".join(params[:len(values)])
            lines.append(f"    result = {func_name}({call_params})")
            lines.append(f'    # Assert')
            lines.append(f"    assert result is not None")
            lines.append(f"    # TODO: 添加具体的断言条件")
            return "\n".join(lines)

        elif self.framework == "jest":
            lines = [f'describe("{func_name}", () => {{']
            lines.append(f'  test("{description}", () => {{')
            lines.append(f'    // Arrange')
            for p, v in zip(params, [values.get(p, "null") for p in params]):
                lines.append(f"    const {p} = {v};")
            lines.append(f'    // Act')
            call_params = ", ".join(params[:len(values)])
            lines.append(f"    const result = {func_name}({call_params});")
            lines.append(f'    // Assert')
            lines.append(f"    expect(result).toBeDefined();")
            lines.append(f"    // TODO: 添加具体的断言条件")
            lines.append("  });")
            lines.append("});")
            return "\n".join(lines)

        elif self.framework == "go-test":
            lines = [f'func Test{func_name.title()}(t *testing.T) {{']
            lines.append(f'\t// {description}')
            lines.append(f'\t// Arrange')
            for p, v in zip(params, [values.get(p, "nil") for p in params]):
                lines.append(f'\t{p} := {v}')
            lines.append(f'\t// Act')
            call_params = ", ".join(params[:len(values)])
            lines.append(f'\tresult := {func_name}({call_params})')
            lines.append(f'\t// Assert')
            lines.append(f'\tif result == nil {{')
            lines.append(f'\t\tt.Errorf("unexpected nil result")')
            lines.append(f'\t}}')
            lines.append("}")
            return "\n".join(lines)

        return ""

    def _build_exception_test(self, func_name: str, params: List[str],
                              values: Dict[str, str], description: str) -> str:
        """构建异常测试代码"""
        if self.framework == "pytest":
            lines = [f'def test_{func_name}_exception():']
            lines.append(f'    """{description}"""')
            lines.append(f'    # Arrange')
            for p, v in zip(params, [values.get(p, "None") for p in params]):
                lines.append(f"    {p} = {v}")
            lines.append(f'    # Act & Assert')
            lines.append(f"    with pytest.raises(Exception):")
            call_params = ", ".join(params[:len(values)])
            lines.append(f"        {func_name}({call_params})")
            return "\n".join(lines)
        return ""

    # ===== 值生成辅助方法 =====
    def _get_normal_values(self, params: List[str]) -> Dict[str, str]:
        return {p: f'"{p}_test_value"' if i % 2 == 0 else str(i + 1)
                for i, p in enumerate(params)}

    def _get_none_values(self, params: List[str]) -> Dict[str, str]:
        return {p: "None" for p in params}

    def _get_zero_values(self, params: List[str]) -> Dict[str, str]:
        return {p: "0" for p in params}

    def _get_large_values(self, params: List[str]) -> Dict[str, str]:
        return {p: "999999999" for p in params}

    def _get_min_values(self, params: List[str]) -> Dict[str, str]:
        return {p: "-999999999" for p in params}

    def _get_max_values(self, params: List[str]) -> Dict[str, str]:
        return {p: "999999999" for p in params}

    def _get_type_mismatch_values(self, params: List[str]) -> Dict[str, str]:
        return {p: "'not_a_number'" for p in params}

    def _get_negative_values(self, params: List[str]) -> Dict[str, str]:
        return {p: "-1" for p in params}

    def _estimate_coverage(self, num_tests: int) -> str:
        if num_tests >= 12:
            return "85-95%"
        elif num_tests >= 8:
            return "70-85%"
        elif num_tests >= 4:
            return "50-70%"
        else:
            return "30-50%"


def main():
    import sys

    if len(sys.argv) < 3:
        print("用法: python test_generator.py <code_file> <function_name> [--framework jest|pytest|go-test]")
        sys.exit(1)

    code_file = sys.argv[1]
    func_name = sys.argv[2]
    framework = "pytest"
    for i, arg in enumerate(sys.argv[3:], 3):
        if arg == "--framework" and i + 1 < len(sys.argv):
            framework = sys.argv[i + 1]

    with open(code_file, "r", encoding="utf-8") as f:
        code = f.read()

    lang = "python"
    if code_file.endswith(".js") or code_file.endswith(".ts"):
        lang = "javascript"
    elif code_file.endswith(".go"):
        lang = "go"

    gen = TestGenerator(language=lang, framework=framework)
    suite = gen.generate(code, func_name)

    # 输出
    if len(sys.argv) > 3 and "--json" in sys.argv:
        print(json.dumps(
            {"function": func_name, "framework": framework,
             "coverage": suite.coverage_estimate,
             "test_cases": [tc.to_dict() for tc in suite.test_cases]},
            indent=2, ensure_ascii=False,
        ))
    else:
        print(suite.to_markdown())
        print("\n--- Generated Test Code ---\n")
        print(suite.to_code())


if __name__ == "__main__":
    main()
